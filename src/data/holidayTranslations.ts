/**
 * Returns the English translation of a Bulgarian holiday name,
 * or the original Bulgarian name if no translation exists.
 */
export function translateHolidayName(name: string, language: string): string {
  if (language !== 'en') return name;
  return holidayNameTranslations[name] || name;
}

/**
 * Returns the English description for a holiday,
 * or the Bulgarian description if no translation exists.
 */
export function translateHolidayDescription(name: string, language: string, bgDescriptions: Record<string, string>): string | undefined {
  if (language === 'en') {
    return holidayDescriptionTranslations[name] || bgDescriptions[name];
  }
  return bgDescriptions[name];
}
